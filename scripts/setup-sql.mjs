// Writes one SQL file that creates every table, for pasting into a hosted database's SQL editor
// (Supabase → SQL Editor). It also fills Prisma's migration history, so later
// `prisma migrate deploy` runs only the migrations added after this file was made.
//   node scripts/setup-sql.mjs > setup.sql
import { createHash, randomUUID } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const dir = "prisma/migrations";
const names = readdirSync(dir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
const out = [
  "-- autobartje: all tables. Generated by scripts/setup-sql.mjs; run once on an empty database.",
  "BEGIN;",
  "",
  `CREATE TABLE "_prisma_migrations" (
  "id" VARCHAR(36) PRIMARY KEY NOT NULL,
  "checksum" VARCHAR(64) NOT NULL,
  "finished_at" TIMESTAMPTZ,
  "migration_name" VARCHAR(255) NOT NULL,
  "logs" TEXT,
  "rolled_back_at" TIMESTAMPTZ,
  "started_at" TIMESTAMPTZ NOT NULL DEFAULT now(),
  "applied_steps_count" INTEGER NOT NULL DEFAULT 0
);`,
];
for (const name of names) {
  const sql = readFileSync(join(dir, name, "migration.sql"), "utf8");
  const checksum = createHash("sha256").update(sql).digest("hex");
  out.push("", `-- ${name}`, sql.trim(), `INSERT INTO "_prisma_migrations" ("id", "checksum", "finished_at", "migration_name", "applied_steps_count") VALUES ('${randomUUID()}', '${checksum}', now(), '${name}', 1);`);
}
out.push("", "COMMIT;", "");
process.stdout.write(out.join("\n"));
